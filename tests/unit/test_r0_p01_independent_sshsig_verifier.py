"""Independent in-process SSHSIG candidate against actual non-owner signatures.

The verifier under test parses SSHSIG and reconstructs the signature payload
in a standalone Node implementation using built-in Ed25519 verification.
It does not import the owner harness or invoke its OpenSSH verification
function. Synthetic signer inputs are generated by the separately existing
non-owner worker, then critical positive/negative results are cross-checked
with actual Windows OpenSSH. No real owner credential, signer prompt,
WebAuthn ceremony or R0-P01 experiment claim is ever requested.
"""
from __future__ import annotations

import base64
import copy
import hashlib
import json
import shutil
import struct
import subprocess
from pathlib import Path

import pytest

from experiments.r0_p01_owner_acceptance_v01 import harness as historical
from experiments.r0_p01_successor_synthetic import run_bound_acceptance as rb

VERIFIER=Path(__file__).parents[2]/"experiments/r0_p01_successor_synthetic/independent_sshsig_verify.mjs"
TEMPLATE=json.loads(
    (Path(historical.HERE)/"clarification_vectors_v02.json").read_text(encoding="utf-8")
)["statement"]
SIGNATURE_HEAD="-----BEGIN SSH SIGNATURE-----"
SIGNATURE_END="-----END SSH SIGNATURE-----"


def call(req):
    result=subprocess.run(
        ["node",str(VERIFIER),"--verify-only"],
        input=json.dumps(req,ensure_ascii=False),capture_output=True,
        text=True,encoding="utf-8",timeout=10,
    )
    assert result.returncode==0,result.stderr
    result_json=json.loads(result.stdout)
    assert set(result_json)>= {"verdict","reason"}
    return result_json


@pytest.fixture(scope="module")
def material():
    if not shutil.which("node") or not shutil.which("ssh-keygen"):
        pytest.skip("Node and real OpenSSH are required for cryptographic comparison")
    message=rb.new_run_statement(TEMPLATE,claim_nonce="2"*64)
    with rb.SyntheticRunCrypto() as node:
        signed=node.call(
            "sign_ssh",label="SYNTHETIC-NON-OWNER-INDEPENDENT-SSHSIG-PRIMARY-001",
            statement=message,
        )
        outsider=node.call(
            "sign_ssh",label="SYNTHETIC-NON-OWNER-INDEPENDENT-SSHSIG-FOREIGN-001",
            statement=message,
        )
        assert signed["credential"]!=outsider["credential"]
        yield message,signed,outsider,node


def request(message,signed):
    return {
        "statement":copy.deepcopy(message),
        "enrolled_public_key":signed["credential"]["public_key"],
        "enrolled_public_id":signed["credential"]["public_id"],
        "proof":copy.deepcopy(signed["proof"]),
    }


def decode(armor):
    lines=armor.strip().splitlines()
    assert lines[0]==SIGNATURE_HEAD and lines[-1]==SIGNATURE_END
    return bytearray(base64.b64decode("".join(lines[1:-1]),validate=True))


def wrap(packet):
    encoded=base64.b64encode(packet).decode("ascii")
    return (
        SIGNATURE_HEAD+"\n"+
        "\n".join(encoded[i:i+70] for i in range(0,len(encoded),70))+
        "\n"+SIGNATURE_END+"\n"
    )


def ssh_s(data):
    return struct.pack(">I",len(data))+data


def split_signature(packet):
    assert packet[:6]==b"SSHSIG" and packet[6:10]==b"\x00\x00\x00\x01"
    offset=10
    fields=[]
    for _ in range(5):
        length=struct.unpack(">I",packet[offset:offset+4])[0]
        offset+=4
        fields.append(bytes(packet[offset:offset+length]))
        offset+=length
    assert offset==len(packet)
    return fields


def change_outer_field(armor,index,value):
    fields=split_signature(decode(armor))
    fields[index]=value
    return wrap(b"SSHSIG"+struct.pack(">I",1)+b"".join(ssh_s(x) for x in fields))


def change_inner_signature_byte(armor):
    fields=split_signature(decode(armor))
    packet=fields[4]
    algo_len=struct.unpack(">I",packet[:4])[0]
    sig_length_pos=4+algo_len
    signature_len=struct.unpack(">I",packet[sig_length_pos:sig_length_pos+4])[0]
    assert signature_len==64
    assert len(packet)==sig_length_pos+4+64
    altered=bytearray(packet)
    altered[-1]^=1
    fields[4]=bytes(altered)
    return wrap(b"SSHSIG"+struct.pack(">I",1)+b"".join(ssh_s(x) for x in fields))


def test_real_ed25519_positive_matches_openssh(material):
    message,signed,_,node=material
    req=request(message,signed)
    verified=call(req)
    assert verified["verdict"]=="VALID"
    assert verified["reason"]=="VERIFIED"
    assert verified["expected_statement_sha256"]==hashlib.sha256(
        historical.canonical(message)
    ).hexdigest()
    assert verified["trusted_public_id"]==signed["credential"]["public_id"]
    assert rb.verify_for_run(
        presented=message,trusted_expected=message,
        proof=signed["proof"],credential=signed["credential"],node=node,
    )


def test_separately_signed_public_identity_also_verifies(material):
    message,_,outsider,node=material
    assert call(request(message,outsider))["verdict"]=="VALID"
    assert rb.verify_for_run(
        presented=message,trusted_expected=message,
        proof=outsider["proof"],credential=outsider["credential"],node=node,
    )


@pytest.mark.parametrize("change",[
    {"decision":"REJECT"},
    {"shown_digest":"a"*64},
    {"semantic_base_digest":"b"*64},
    {"envelope_digest":"c"*64},
    {"claim_nonce":"f"*64},
    {"issued_at":"2099-01-01T00:00:00+00:00"},
])
def test_signed_statement_changes_are_rejected_cryptographically(
    material,change,
):
    message,signed,_,node=material
    req=request({**message,**change},signed)
    assert rb.valid_shape(req["statement"])
    assert call(req)["verdict"]=="INVALID"
    assert not rb.verify_for_run(
        presented=req["statement"],trusted_expected=req["statement"],
        proof=signed["proof"],credential=signed["credential"],node=node,
    )


def test_embedded_public_key_cannot_impersonate_enrolled_signer(material):
    message,signed,outsider,_=material
    req=request(message,signed)
    req["proof"]=outsider["proof"]
    assert call(req)=={"verdict":"INVALID","reason":"EMBEDDED_SIGNER"}


def test_changing_trusted_public_id_is_not_allowed(material):
    message,signed,_,_=material
    req=request(message,signed)
    req["enrolled_public_id"]="SSH-ED25519-SHA256-HEX:"+"a"*64
    assert call(req)["reason"]=="TRUSTED_PUBLIC_ID"


def test_real_signature_bitflip_keeps_packet_valid_but_is_rejected(material):
    message,signed,_,node=material
    req=request(message,signed)
    req["proof"]["sshsig"]=change_inner_signature_byte(req["proof"]["sshsig"])
    verdict=call(req)
    assert (verdict["verdict"],verdict["reason"])==("INVALID","SIGNATURE_REJECTED")
    assert verdict["expected_statement_sha256"]==hashlib.sha256(
        historical.canonical(message)
    ).hexdigest()
    assert not rb.verify_for_run(
        presented=message,trusted_expected=message,
        proof=req["proof"],credential=signed["credential"],node=node,
    )


@pytest.mark.parametrize("index,value,expected",[
    (1,b"unrelated-space","WRONG_NAMESPACE"),
    (2,b"not empty","NONEMPTY_RESERVED"),
    (3,b"sha256","WRONG_HASH"),
])
def test_grammatically_valid_but_wrong_sshsig_domain_rejected(
    material,index,value,expected,
):
    message,signed,_,_=material
    req=request(message,signed)
    req["proof"]["sshsig"]=change_outer_field(req["proof"]["sshsig"],index,value)
    assert call(req)=={"verdict":"INVALID","reason":expected}


def test_invalid_inner_algorithm_rejected(material):
    message,signed,_,_=material
    req=request(message,signed)
    fields=split_signature(decode(req["proof"]["sshsig"]))
    fields[4]=ssh_s(b"ssh-rsa")+ssh_s(b"0"*64)
    req["proof"]["sshsig"]=wrap(
        b"SSHSIG"+struct.pack(">I",1)+b"".join(ssh_s(x) for x in fields)
    )
    assert call(req)["reason"]=="WRONG_ALGORITHM"


@pytest.mark.parametrize("mutator,expected",[
    (lambda b: b[:6]+struct.pack(">I",2)+b[10:],"SSHSIG_VERSION"),
    (lambda b: b+b"x","TRAILING_SSH_BYTES"),
    (lambda b: b[:10]+struct.pack(">I",0xffffffff)+b[14:],"TRUNCATED_SSH_STRING"),
])
def test_framing_errors_are_rejected(material,mutator,expected):
    message,signed,_,_=material
    req=request(message,signed)
    req["proof"]["sshsig"]=wrap(mutator(bytes(decode(req["proof"]["sshsig"]))))
    assert call(req)["reason"]==expected


@pytest.mark.parametrize("tamper",[
    "partial","bad_base64","extra_newline","empty","wrong_kind",
])
def test_malformed_armor_or_kind_does_not_verify(material,tamper):
    message,signed,_,_=material
    req=request(message,signed)
    if tamper=="partial":
        req["proof"]["sshsig"]=req["proof"]["sshsig"][:90]
    elif tamper=="bad_base64":
        req["proof"]["sshsig"]=req["proof"]["sshsig"].replace(
            SIGNATURE_HEAD,SIGNATURE_HEAD+"\n!",
        )
    elif tamper=="extra_newline":
        req["proof"]["sshsig"]=req["proof"]["sshsig"].replace(
            SIGNATURE_HEAD,SIGNATURE_HEAD+"\n",
        )
    elif tamper=="empty":
        req["proof"]["sshsig"]=""
    else:
        req["proof"]["kind"]="WEBAUTHN_ES256"
    assert call(req)["verdict"]=="INVALID"


@pytest.mark.parametrize("tamper",[
    "unknown_field","missing_field","invalid_nonce","wrong_protocol","non_string",
])
def test_statement_schema_and_protocol_also_fail_closed(material,tamper):
    message,signed,_,_=material
    req=request(message,signed)
    if tamper=="unknown_field":
        req["statement"]["forged"]="x"
    elif tamper=="missing_field":
        del req["statement"]["acceptance_id"]
    elif tamper=="invalid_nonce":
        req["statement"]["claim_nonce"]="BAD"
    elif tamper=="wrong_protocol":
        req["statement"]["protocol"]="OTHER"
    else:
        req["statement"]["decision"]=42
    assert call(req)["verdict"]=="INVALID"


def test_trusted_context_is_required_not_deduced_from_proof(material):
    message,signed,_,_=material
    req=request(message,signed)
    del req["enrolled_public_key"]
    assert call(req)["reason"]=="REQUEST_FIELDS"


