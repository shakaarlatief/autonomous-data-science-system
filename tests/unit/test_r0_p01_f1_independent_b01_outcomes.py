def test_existing_unreviewed_288_row_seed_diagnostic_only():
    draft=json.loads(DRAFT.read_text(encoding="utf-8"))
    assert draft["status"]=="F1_CANDIDATE_ORACLE_DATA_UNREVIEWED_NOT_FROZEN"
    assert len(draft["cases"])==288

    mismatches=[]
    requires_numeric=[]
    for case in draft["cases"]:
        args=case["inputs"]
        actual=classify_b01(**args)
        if actual["status"]=="PENDING_NUMERIC_SELECTION":
            # The old candidate labels BOTH_ELIGIBLE from an unspecified
            # winner and a single volume boolean; this is not a final oracle.
            requires_numeric.append(case["id"])
            continue
        current={k:actual[k] for k in case["expected"]}
        if current != case["expected"]:
            mismatches.append((case["id"], current, case["expected"]))
    assert not mismatches, f"candidate B01 disagreements: {mismatches[:5]!r}"
    assert requires_numeric, "both eligible needs real numeric selection"
    # This validates ONLY the predicate-complete rows of an unreviewed seed.
    # It cannot freeze semantic flags, numerical selection, or evidence sites.

@pytest.mark.parametrize(
    "data",
    [
        ("54","70","58","72","B",False,"AMEND"),
        ("50","70","60","72","A",True,"PASS_WITH_SELECTION"),
        ("55","85","50","70","B",True,"PASS_WITH_SELECTION"),
        ("50","70","55","85","A",True,"PASS_WITH_SELECTION"),
        ("54","75","55","74","B",True,"PASS_WITH_SELECTION"),
        ("55","70","56","70","B",False,"AMEND"),
        ("50","50","60","50","A",True,"PASS_WITH_SELECTION"),
    ],
    ids=[f"NUMERICAL-COMPLETE-{i:02d}" for i in range(1, 8)],
)
def test_source_thresholds_yield_expected_complete_numerical_outcomes(data):
    a_s,a_l,b_s,b_l,winner,volume_pass,expected_class=data
    actual_winner=select_arm_exact(a_s,a_l,b_s,b_l)
    assert actual_winner==winner
    actual_volume=projected_volume_gate(a_s if winner=="A" else b_s)
    assert actual_volume is volume_pass
    output=classify_b01(
        A=CE,B=CE,integrity_flag=False,instrument_flag=False,
        volume_gate_pass=actual_volume,selected_arm=actual_winner,
    )
    assert output["status"]=="DETERMINED"
    assert output["class"]==expected_class
    assert output["arm_selection"]==(winner if volume_pass else "NONE")


